/**
 * Iconos propios de RCKTDMG (trazo 1.5, esquinas redondeadas).
 *
 * Misma API que lucide-react para poder cambiarlos sin tocar el resto:
 *   <IconoBolsa size={18} aria-hidden className="…" />
 * El color sale de `currentColor`, así que heredan el color del texto
 * en los dos temas. `strokeWidth` por defecto 1.5 (el del diseño).
 */

export type IconoProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  size?: number | string;
  strokeWidth?: number | string;
};

function crear(nombre: string, cuerpo: React.ReactNode) {
  const Icono = forwardRef<SVGSVGElement, IconoProps>(function Icono(
    { size = 24, strokeWidth = 1.5, ...resto },
    ref
  ) {
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        {...resto}
      >
        {cuerpo}
      </svg>
    );
  });

  Icono.displayName = nombre;

  return Icono;
}

